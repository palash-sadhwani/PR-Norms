def run(*args: str, cwd: Path) -> str:
    return subprocess.run(args, cwd=cwd, check=True, capture_output=True, text=True).stdout


def write_files(root: Path, files: dict[str, str]) -> None:
    for name, content in files.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)


def commit(root: Path, message: str) -> None:
    run("git", "add", "-A", cwd=root)
    run("git", "commit", "-q", "-m", message, cwd=root)


def build_git(root: Path) -> None:
    if root.exists():
        raise SystemExit(f"{root} exists; choose a new directory")
    root.mkdir(parents=True)
    run("git", "init", "-q", "-b", "main", cwd=root)
    write_files(root, MAIN_FILES)
    commit(root, "Initial inventory service")
    for scenario in SCENARIOS:
        run("git", "checkout", "-q", "-b", scenario["branch"], "main", cwd=root)
        write_files(root, scenario["files"])
        commit(root, scenario["title"])
        if "fix_files" in scenario:
            run("git", "checkout", "-q", "-b", scenario["branch"] + "-fix", cwd=root)
            write_files(root, scenario["fix_files"])
            commit(root, "Address review feedback")
        run("git", "checkout", "-q", "main", cwd=root)
    print(f"Built {root} with {len(SCENARIOS)} scenario branches")


class GitHub:
    def __init__(self, repository: str) -> None:
        self.base = f"https://api.github.com/repos/{repository}"
        self.token = os.environ.get("GITHUB_TOKEN")

    def call(self, method: str, path: str, body: dict | None = None):
        headers = {"Accept": "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28"}
        if self.token:
            headers["Authorization"] = f"Bearer {self.token}"
        data = json.dumps(body).encode() if body is not None else None
        if data is not None:
            headers["Content-Type"] = "application/json"
        request = urllib.request.Request(self.base + path, data=data, method=method, headers=headers)
        try:
            with urllib.request.urlopen(request, timeout=30) as response:
                text = response.read()
                return json.loads(text) if text else None
        except urllib.error.HTTPError as exc:
            raise SystemExit(f"{method} {path} failed: {exc.code} {exc.read()[:300]!r}") from exc


def line_of(content: str, needle: str) -> int:
    for number, line in enumerate(content.splitlines(), start=1):
        if needle in line:
            return number
    raise ValueError(f"{needle!r} not found")


def populate(root: Path, repository: str) -> None:
    github = GitHub(repository)
    branches = [s["branch"] for s in SCENARIOS] + [
        s["branch"] + "-fix" for s in SCENARIOS if "fix_files" in s
    ]
    remote = run("git", "ls-remote", "--heads", "origin", cwd=root)
    missing = [
        f"{b}:{b}"
        for b in ["main", *branches]
        if not b.endswith("-fix") and f"refs/heads/{b}\n" not in remote + "\n"
    ]
    if missing:  # never re-push over branches that already moved on GitHub
        run("git", "push", "-q", "origin", *missing, cwd=root)
    existing = {pr["head"]["ref"]: pr for pr in github.call("GET", "/pulls?state=all&per_page=100")}
    for scenario in SCENARIOS:
        branch = scenario["branch"]
        pr = existing.get(branch) or github.call(
            "POST",
            "/pulls",
            {"title": scenario["title"], "head": branch, "base": "main",
             "body": f"{scenario['body']}\n\n_{NOTICE}_" + FOOTER},
        )
        number = pr["number"]
        print(f"#{number} {scenario['title']}")
        if scenario.get("open"):
            continue
        if not github.call("GET", f"/pulls/{number}/reviews"):
            head = run("git", "rev-parse", branch, cwd=root).strip()
            github.call(
                "POST",
                f"/pulls/{number}/reviews",
                {
                    "commit_id": head,
                    "event": "COMMENT",
                    "body": scenario["review"] + FOOTER,
                    "comments": [
                        {"path": path, "line": line_of(scenario["files"][path], at),
                         "side": "RIGHT", "body": body + FOOTER}
                        for path, at, body in scenario["comments"]
                    ],
                },
            )
        if pr.get("merged_at"):
            continue
        run("git", "push", "-q", "origin", f"{branch}-fix:{branch}", cwd=root)
        if not github.call("GET", f"/issues/{number}/comments"):
            github.call("POST", f"/issues/{number}/comments", {"body": scenario["reply"] + FOOTER})
        for _ in range(10):  # mergeability is computed asynchronously after a push
            try:
                github.call("PUT", f"/pulls/{number}/merge", {"merge_method": "merge"})
                break
            except SystemExit as exc:
                if " 405 " not in str(exc) and " 409 " not in str(exc):
                    raise
                time.sleep(3)


def main() -> None:
    if len(sys.argv) != 3 or sys.argv[1] not in {"git", "populate"}:
        raise SystemExit(__doc__)
    if sys.argv[1] == "git":
        build_git(Path(sys.argv[2]).resolve())
    else:
        populate(Path.cwd(), sys.argv[2])


if __name__ == "__main__":
    main()
